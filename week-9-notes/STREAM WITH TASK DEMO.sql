    CREATE OR REPLACE TASK PROCESS_NEW_ORDERS_TASK
    WAREHOUSE=TASK_DEMO_WH
    SCHEDULE='1 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('ORDER_STREAM')
    AS
    INSERT INTO PROCESSED_ORDERS
    (ORDER_ID,CUSTOMER_NAME,PRODUCT_NAME,ORDER_AMOUNT,ORDER_DATE,PROCESSED_TIME)
    SELECT
    ORDER_ID,CUSTOMER_NAME,PRODUCT_NAME,ORDER_AMOUNT,ORDER_DATE,CURRENT_TIMESTAMP()
    FROM ORDER_STREAM
    WHERE METADATA$ACTION='INSERT'
    AND METADATA$ISUPDATE=FALSE;


    ALTER TASK PROCESS_NEW_ORDERS_TASK RESUME;

    SHOW TASKS;

    SELECT * FROM PROCESSED_ORDERS;

    EXECUTE TASK PROCESS_NEW_ORDERS_TASK;

    ALTER TASK PROCESS_NEW_ORDERS_TASK SUSPEND;

