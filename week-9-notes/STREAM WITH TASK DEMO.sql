USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE DATABASE TASK_DEMO_DB;

CREATE OR REPLACE SCHEMA TASK_DEMO_DB.ECOMMERCE;

USE DATABASE TASK_DEMO_DB;
USE SCHEMA ECOMMERCE;

CREATE OR REPLACE WAREHOUSE TASK_DEMO_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE TABLE ORDERS
(
    ORDER_ID       NUMBER,
    CUSTOMER_NAME  VARCHAR,
    PRODUCT_NAME   VARCHAR,
    ORDER_AMOUNT   NUMBER(10,2),
    ORDER_DATE     TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

SELECT * FROM ORDERS;

CREATE OR REPLACE TABLE PROCESSED_ORDERS
(
    ORDER_ID        NUMBER,
    CUSTOMER_NAME   VARCHAR,
    PRODUCT_NAME    VARCHAR,
    ORDER_AMOUNT    NUMBER(10,2),
    ORDER_DATE      TIMESTAMP,
    PROCESSED_TIME  TIMESTAMP
);


SELECT * FROM  PROCESSED_ORDERS;

CREATE OR REPLACE STREAM ORDER_STREAM
ON TABLE ORDERS;

