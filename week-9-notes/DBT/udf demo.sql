-- UDF SYNTAX

CREATE OR REPLACE FUNCTION DOUBLE_VALUE(NUMBER_VALUE NUMBER)
RETURNS NUMBER
LANGUAGE SQL
AS
$$
    NUMBER_VALUE*2
$$;

SELECT  DOUBLE_VALUE(4);

SELECT  DOUBLE_VALUE(12);


CREATE OR REPLACE FUNCTION ADD_TAX(AMOUNT NUMBER)
RETURNS NUMBER
LANGUAGE SQL
AS
$$
    AMOUNT * 1.18
$$;


SELECT ADD_TAX(1000);

SELECT 
CUSTOMER_NAME,
TOTAL_SPEND, 
ADD_TAX(TOTAL_SPEND) AS AMOUNT_WITH_TAX
FROM CUSTOMERS;



--SCALAR UDF

CREATE OR REPLACE FUNCTION GET_CUSTOMER_CATEGORY(TOTAL_AMOUNT NUMBER)
RETURNS  VARCHAR
LANGUAGE SQL
AS
$$
    CASE 
        WHEN TOTAL_AMOUNT> 40000 THEN 'VIP'
        WHEN TOTAL_AMOUNT>= 20000 THEN 'PREMIUM'
        ELSE 'STANDARD'
    END
$$;

SELECT GET_CUSTOMER_CATEGORY(34000);


