CREATE OR REPLACE FUNCTION AGE_GROUP(AGE_VALUE NUMBER)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
    CASE
        WHEN AGE_VALUE <30 THEN 'YOUNG ADULT'
        WHEN AGE_VALUE <40 THEN 'ADULT'
        ELSE 'SENIOR CUSTOMER'
    END
$$;

SELECT CUSTOMER_NAME,
AGE,
AGE_GROUP(AGE) AS AGE_CATEGORY
FROM CUSTOMERS 
ORDER BY AGE;

SELECT
CUSTOMER_ID,
CUSTOMER_LABEL(CUSTOMER_NAME,COUNTRY) AS CUSTOEMR,
AGE_GROUP(AGE) AS AGE_GROUP,
GET_CUSTOMER_CATEGORY(TOTAL_SPEND) AS SPENDING_CATEGORY
FROM CUSTOMERS;


