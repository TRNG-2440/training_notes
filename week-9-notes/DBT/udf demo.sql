-- UDF WITH MULTIPLE PARAMETERS

CREATE OR REPLACE FUNCTION CUSTOMER_LABEL(NAME VARCHAR,COUNTRY_NAME VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
 NAME || ' - ' || COUNTRY_NAME
$$;


SELECT CUSTOMER_LABEL('Tina','Canada')

