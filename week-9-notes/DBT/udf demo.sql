SELECT
GET_CUSTOMER_CATEGORY(TOTAL_SPEND) AS CUSTOMER_CATEGORY,
 COUNT(*) AS CUSTOMER_COUNT,
 SUM(TOTAL_SPEND) AS TOTAL_REVENUE
 FROM CUSTOMERS
 GROUP BY GET_CUSTOMER_CATEGORY(TOTAL_SPEND)
 ORDER BY TOTAL_REVENUE DESC;


